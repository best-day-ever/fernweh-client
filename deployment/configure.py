#!/usr/bin/env python3
"""Validate public deployment settings and generate the Client's build header."""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

BROKER_RESOURCES = {
    "backend/fernweh-install-update.ps1", "gui/RemoteView.qml",
    "gui/RemoteWorkstationCard.qml", "gui/OnboardingView.qml", "gui/OnboardingQrCode.qml",
    "gui/BrokerUsernameField.qml", "gui/BrokerSessionBanner.qml",
}


def broker_enabled(environ):
    value = environ.get("FERNWEH_BROKER_ENABLED", "0")
    if value not in ("0", "1"):
        raise ValueError("FERNWEH_BROKER_ENABLED must be 0 or 1")
    return value == "1"


def dns_name(value, key, allow_ip=False):
    if not value:
        return value
    try:
        address = ipaddress.ip_address(value)
    except ValueError:
        address = None
    if address is not None:
        if allow_ip and address.version == 4:
            return value
        raise ValueError(f"{key} must be a DNS name")
    if len(value) > 253 or any(not re.fullmatch(
            r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", label)
            for label in value.split(".")):
        raise ValueError(f"{key} must be a plain DNS name without a scheme or port")
    return value


def settings(environ):
    enabled = broker_enabled(environ)
    if not enabled:
        # Explicitly disabled builds ignore saved studio build environments.
        # None of those values enter the executable or trigger dependencies.
        return {"BrokerEnabled": False, "BrokerHost": "", "BrokerPort": 29000,
                "BrokerPins": "", "PasskeyRpId": "", "UpdatesEnabled": False}
    host = dns_name(environ.get("FERNWEH_BROKER_HOST", "").strip().lower(),
                    "FERNWEH_BROKER_HOST", allow_ip=True)
    raw_port = environ.get("FERNWEH_BROKER_PORT", "29000")
    if not re.fullmatch(r"[0-9]{1,5}", raw_port) or not 1 <= int(raw_port) <= 65535:
        raise ValueError("FERNWEH_BROKER_PORT must be 1..65535")
    pins = []
    raw_pins = environ.get("FERNWEH_BROKER_PINS", "").strip()
    if raw_pins:
        for pin in raw_pins.split(","):
            pin = pin.strip().lower()
            if not re.fullmatch(r"[0-9a-f]{64}", pin):
                raise ValueError("FERNWEH_BROKER_PINS needs comma-separated SHA-256 hex pins")
            if pin not in pins:
                pins.append(pin)
    if bool(host) != bool(pins):
        raise ValueError("FERNWEH_BROKER_HOST and FERNWEH_BROKER_PINS must be set together")
    rp_id = dns_name(environ.get("FERNWEH_PASSKEY_RP_ID", "").strip().lower(),
                     "FERNWEH_PASSKEY_RP_ID")
    updates = environ.get("FERNWEH_UPDATES_ENABLED", "0")
    if updates not in ("0", "1"):
        raise ValueError("FERNWEH_UPDATES_ENABLED must be 0 or 1")
    if updates == "1" and not host:
        raise ValueError("FERNWEH_UPDATES_ENABLED requires a configured, pinned broker")
    return {"BrokerEnabled": True, "BrokerHost": host, "BrokerPort": int(raw_port),
            "BrokerPins": ",".join(pins), "PasskeyRpId": rp_id,
            "UpdatesEnabled": updates == "1"}


def generate(config):
    lines = ["// Generated by deployment/configure.py; rerun qmake after changes.",
             "#pragma once", f"#define FERNWEH_BROKER_ENABLED {int(config['BrokerEnabled'])}",
             "namespace FernwehDeployment {"]
    for key, value in config.items():
        if isinstance(value, str):
            lines.append(f"inline constexpr char {key}[] = {json.dumps(value)};")
        elif isinstance(value, bool):
            lines.append(f"inline constexpr bool {key} = {'true' if value else 'false'};")
        else:
            lines.append(f"inline constexpr unsigned short {key} = {value};")
    return "\n".join(lines + ["}", ""])


def profile_qml(source, enabled):
    """Select explicitly delimited broker sections without changing QRC URLs."""
    depth = 0
    result = []
    for line in source.splitlines(keepends=True):
        marker = line.strip()
        if marker == "// @fernweh-broker-begin":
            depth += 1
        elif marker == "// @fernweh-broker-end":
            if not depth:
                raise ValueError("Unbalanced Fernweh broker QML section")
            depth -= 1
        elif enabled or not depth:
            result.append(line)
    if depth:
        raise ValueError("Unclosed Fernweh broker QML section")
    return "".join(result)


def write_if_changed(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != content:
        path.write_text(content, encoding="utf-8")


def resources(output, enabled):
    app = Path(__file__).resolve().parents[1] / "app"
    document = ET.parse(app / "qml.qrc")
    for group in document.getroot():
        for entry in list(group):
            name = entry.text.strip()
            if not enabled and name in BROKER_RESOURCES:
                group.remove(entry)
                continue
            entry.set("alias", entry.get("alias", name))
            source = app / name
            if name in ("gui/main.qml", "gui/SettingsView.qml", "gui/DisplaySetupDialog.qml", "gui/DisplayAdvancedPage.qml"):
                generated = output / name
                write_if_changed(generated, profile_qml(source.read_text(encoding="utf-8"), enabled))
                source = generated
            entry.text = str(source.resolve())
    write_if_changed(output / "qml.qrc", ET.tostring(document.getroot(), encoding="unicode") + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--qml-output", type=Path)
    args = parser.parse_args()
    try:
        config = settings(os.environ)
        content = generate(config)
        if args.qml_output:
            resources(args.qml_output, config["BrokerEnabled"])
        write_if_changed(args.output, content)
    except (ValueError, OSError) as error:
        # Values never enter diagnostics: build logs can be shared publicly.
        print(f"Fernweh configuration failed: {error}" if isinstance(error, ValueError)
              else "Fernweh configuration header could not be written", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
